"""The colony's knowledge base: Concept, Tool, Workflow and Playbook cards (castes/nurse.md)."""
from __future__ import annotations

from pathlib import Path

from .gates.knowledge import KINDS, front_matter

TEMPLATE_NAMES = ("Concept", "Tool", "Workflow", "Playbook")
TEMPLATES = Path(__file__).parent / "templates" / "knowledge"


def index(root: str | Path) -> tuple[int, list[str]]:
    """Write knowledge/INDEX.md: every card by kind, with its use case and complexity. Returns (status, report)."""
    kb = Path(root).resolve() / "knowledge"
    if not kb.is_dir():
        return 1, ["no knowledge/ folder here; run `apiary init` first"]
    lines = ["# Knowledge index", "",
             "Generated by `apiary knowledge index`. Cards follow the Digital-ToolBox format; see `_templates/`.", ""]
    total = 0
    for folder in KINDS:
        cards = sorted((kb / folder).glob("*.md"))
        lines += [f"## {folder} ({len(cards)})", ""]
        if cards:
            lines += ["| Card | Use case | Complexity |", "|---|---|---|"]
        for p in cards:
            fm = front_matter(p.read_text(encoding="utf-8", errors="replace")) or {}
            uses = fm.get("use_cases") or fm.get("Use Case") or [""]
            use = uses[0] if isinstance(uses, list) and uses else str(uses)
            lines.append(f"| [[{p.stem}]] | {use.replace('|', '/')} | {fm.get('complexity', '')} |")
        lines.append("")
        total += len(cards)
    (kb / "INDEX.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return 0, [f"wrote knowledge/INDEX.md ({total} cards)"]
